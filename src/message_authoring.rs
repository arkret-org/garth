    #[test]
    fn a_queued_prepared_message_is_never_re_authored_locally() {
        let sender = CountingSender::default();
        let session = session(sender.encrypt(), 15);
        let outcome = station_prepare(session.request());
        let submission = session.sign(&outcome, created_at(), proof_only).unwrap();
        let queued = crate::QueuedSdkEvent::station_prepared_message(
            crate::StationPreparedMessageRecord {
                request_id: submission.request_id.clone(),
                request_digest: submission.request_digest.clone(),
                expires_at: submission.expires_at,
            },
            submission.event.clone(),
            "local-message:1".to_owned(),
            submission.canonical_body_bytes.clone(),
            generation(),
        )
        .unwrap();
        assert!(queued.requires_new_preparation());
        let attempt = queued.authored_attempt.as_ref().unwrap();
        assert_eq!(
            attempt.transport_idempotency_key,
            submission.transport_idempotency_key()
        );
        assert_eq!(
            attempt.canonical_body_bytes,
            submission.canonical_body_bytes
        );
        // The authority the user signed travels with the slot instead of being
        // resolved again on the next attempt.
        assert_eq!(
            queued.intent.auth_context(),
            submission.event.event().auth_context.as_ref()
        );
        queued.validate().unwrap();
        let restored: crate::QueuedSdkEvent =
            serde_json::from_slice(&serde_json::to_vec(&queued).unwrap()).unwrap();
        restored.validate().unwrap();
        assert!(restored.requires_new_preparation());

        let mut unsigned = submission.event.clone();
        unsigned.clear_proofs();
        assert!(
            crate::QueuedSdkEvent::station_prepared_message(
                crate::StationPreparedMessageRecord {
                    request_id: submission.request_id.clone(),
                    request_digest: submission.request_digest.clone(),
                    expires_at: submission.expires_at,
                },
                unsigned,
                "local-message:1".to_owned(),
                submission.canonical_body_bytes.clone(),
                generation(),
            )
            .is_err()
        );
        assert_eq!(sender.calls(), 1);
    }

