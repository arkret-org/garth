//! The one ordinary-message authoring path.
//!
//! An application hands this module a closed typed intent whose body is
//! already encrypted (or, where the target policy still allows it, plaintext).
//! From there the path is fixed:
//!
//! ```text
//! typed intent -> Station prepare -> local verify -> proof-only signature -> Event submit
//! ```
//!
//! Nothing here constructs an Event envelope, resolves an actor frontier, picks
//! an authorization closure or chooses a CBS basis: those are the Station's
//! answers, and the client's job is to refuse them when they do not match what
//! it independently knows. The encrypted body is produced exactly once, before
//! the first request, and is never regenerated by a retry — re-encrypting would
//! consume another MLS sender counter for a message the user authored once.
//!
//! What is deliberately NOT here: the MLS engine (the host encrypts and hands
//! in the finished envelope), the producer signer (the host signs through a
//! closure), and the durable submit queue (that stays [`crate::outbound`]).

