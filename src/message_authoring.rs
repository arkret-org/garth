    #[tokio::test]
    async fn registered_failures_map_to_their_own_recovery() {
        let session = session(plaintext(), 11);
        let cases = [
            (
                api_error(403, "capability_denied", "authorization is not sealed"),
                MessageAuthoringRecovery::RetrySameRequest,
                true,
            ),
            (
                api_error(503, "frontier_unavailable", "seal head is unavailable"),
                MessageAuthoringRecovery::RetrySameRequest,
                true,
            ),
            (
                api_error(410, "authoring_request_expired", "expired"),
                MessageAuthoringRecovery::RePrepareSameBody,
                false,
            ),
            (
                api_error(412, "failed_precondition", "group state moved"),
                MessageAuthoringRecovery::ReEncrypt,
                false,
            ),
            (
                api_error(409, "duplicate_conflict", "another intent"),
                MessageAuthoringRecovery::FailClosed,
                false,
            ),
            (
                api_error(403, "e2ee_required", "plaintext is not permitted"),
                MessageAuthoringRecovery::FailClosed,
                false,
            ),
            (
                api_error(409, "cas_conflict", "actor chain moved"),
                MessageAuthoringRecovery::RePrepareSameBody,
                false,
            ),
        ];
        for (error, recovery, not_ready) in cases {
            let station = ScriptedStation::failing(error);
            let failure = session.prepare(&station).await.unwrap_err();
            assert_eq!(failure.recovery(), recovery, "{failure}");
            assert_eq!(failure.is_not_ready(), not_ready, "{failure}");
        }
        let station = ScriptedStation::failing(Error::Http("connection reset".to_owned()));
        let failure = session.prepare(&station).await.unwrap_err();
        assert_eq!(
            failure.recovery(),
            MessageAuthoringRecovery::ReplayExactSubmission
        );
    }

