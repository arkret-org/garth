#[cfg(not(target_arch = "wasm32"))]
pub type BoxMessageAuthoringFuture<'a, T> = Pin<Box<dyn Future<Output = Result<T>> + Send + 'a>>;
#[cfg(target_arch = "wasm32")]
pub type BoxMessageAuthoringFuture<'a, T> = Pin<Box<dyn Future<Output = Result<T>> + 'a>>;

/// The account's own Station, asked to complete one unsigned Event.
pub trait MessagePrepareTransport: MaybeSendSync {
    fn prepare_message<'a>(
        &'a self,
        request: &'a MessagePrepareRequestBody,
    ) -> BoxMessageAuthoringFuture<'a, MessagePrepareOutcome>;
}

impl MessagePrepareTransport for arkret_http_client::Client {
    fn prepare_message<'a>(
        &'a self,
        request: &'a MessagePrepareRequestBody,
    ) -> BoxMessageAuthoringFuture<'a, MessagePrepareOutcome> {
        Box::pin(async move {
            self.self_message_prepare(request)
                .await
                .map_err(Error::from)
        })
    }
}

/// Everything the client already knows about the target, independently of the
/// Station answer it is about to check.
///
/// `authorization_context` is the accepted Realm authority head this client
/// verified for itself; `known_frontier` is its own view of the actor chain.
/// Both exist so a Station cannot quietly move the message to another scope,
/// another authority closure or another chain position.
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct MessageAuthoringTarget {
    pub scope: ScopeRef,
    pub authorization_context: AuthContext,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub direct_binding: Option<EventId>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub known_frontier: Option<RealmActorFrontierView>,
}

/// What the client should do next after a preparation or submission failed.
///
/// These are recovery classes, not error codes: every one of them answers the
/// only question the send state machine has, which is whether the exact same
/// bytes may be sent again, whether a new preparation identity is required, and
/// whether the body has to be encrypted again under a changed context.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum MessageAuthoringRecovery {
    /// Retry the identical request once the named dependency is available.
    RetrySameRequest,
    /// Prepare again with a new request identity and the identical body.
    ///
    /// The encrypted body is reused verbatim: a preparation that expired or was
    /// definitely not accepted consumed no MLS sender state.
    RePrepareSameBody,
    /// The frozen encryption context no longer applies. A new attempt has to
    /// encrypt again under the current context, which is the only case where
    /// the MLS sender counter legitimately advances a second time.
    ReEncrypt,
    /// The submission may already have landed. Only an exact replay of the
    /// stored canonical bytes, proof and idempotency identity is allowed.
    ReplayExactSubmission,
    /// Fail closed. Nothing about retrying changes the answer.
    FailClosed,
}

/// Why one ordinary-message attempt did not produce an accepted Event.
///
/// The variants exist so a UI can say what is actually wrong. A single
/// "could not send" line hides the difference between "your authorization is
/// not sealed yet, this will clear on its own" and "this Station changed the
/// message you were about to sign".
/// Deliberately exhaustive: a consumer that renders these has to say something
/// true about every one of them, and a wildcard arm is how "send failed" comes
/// back.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum MessageAuthoringFailure {
    /// Authorization exists locally but is not yet covered by an accepted Seal.
    /// This is the new-member window, and it clears without user action.
    AuthorizationNotSealed { detail: String },
    /// A security dependency the Station needs is momentarily unavailable.
    DependencyUnavailable { detail: String },
    /// The target refuses a plaintext body. The encrypted branch is required.
    PlaintextRefused { detail: String },
    /// The frozen MLS binding no longer matches the accepted group state.
    EncryptionContextChanged { detail: String },
    /// The preparation window closed.
    PreparationExpired { detail: String },
    /// This request identity already carries different bytes.
    DuplicateConflict { detail: String },
    /// The Station did not return the exact closed intent. Never sign this.
    PreparedIntentMismatch { detail: String },
    /// The actor chain moved under a frozen prepared Event.
    ActorChainConflict { detail: String },
    /// Transport failed after the request left, so acceptance is unknown.
    SubmissionOutcomeUnknown { detail: String },
    /// Anything the contract rejects outright.
    Refused { code: String, detail: String },
}

impl MessageAuthoringFailure {
    pub fn recovery(&self) -> MessageAuthoringRecovery {
        match self {
            Self::AuthorizationNotSealed { .. } | Self::DependencyUnavailable { .. } => {
                MessageAuthoringRecovery::RetrySameRequest
            }
            Self::PreparationExpired { .. } | Self::ActorChainConflict { .. } => {
                MessageAuthoringRecovery::RePrepareSameBody
            }
            Self::EncryptionContextChanged { .. } => MessageAuthoringRecovery::ReEncrypt,
            Self::SubmissionOutcomeUnknown { .. } => {
                MessageAuthoringRecovery::ReplayExactSubmission
            }
            Self::PlaintextRefused { .. }
            | Self::DuplicateConflict { .. }
            | Self::PreparedIntentMismatch { .. }
            | Self::Refused { .. } => MessageAuthoringRecovery::FailClosed,
        }
    }

    /// True while the send is still expected to succeed on its own.
    pub fn is_not_ready(&self) -> bool {
        matches!(
            self,
            Self::AuthorizationNotSealed { .. } | Self::DependencyUnavailable { .. }
        )
    }

    pub fn detail(&self) -> &str {
        match self {
            Self::AuthorizationNotSealed { detail }
            | Self::DependencyUnavailable { detail }
            | Self::PlaintextRefused { detail }
            | Self::EncryptionContextChanged { detail }
            | Self::PreparationExpired { detail }
            | Self::DuplicateConflict { detail }
            | Self::PreparedIntentMismatch { detail }
            | Self::ActorChainConflict { detail }
            | Self::SubmissionOutcomeUnknown { detail }
            | Self::Refused { detail, .. } => detail,
        }
    }
}

impl std::fmt::Display for MessageAuthoringFailure {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::AuthorizationNotSealed { detail } => write!(
                formatter,
                "message authorization is not covered by an accepted Seal yet: {detail}"
            ),
            Self::DependencyUnavailable { detail } => write!(
                formatter,
                "a security dependency for this message is unavailable: {detail}"
            ),
            Self::PlaintextRefused { detail } => write!(
                formatter,
                "this target requires end-to-end encryption: {detail}"
            ),
            Self::EncryptionContextChanged { detail } => write!(
                formatter,
                "the frozen encryption context no longer applies: {detail}"
            ),
            Self::PreparationExpired { detail } => {
                write!(formatter, "message preparation expired: {detail}")
            }
            Self::DuplicateConflict { detail } => write!(
                formatter,
                "this preparation identity already carries different content: {detail}"
            ),
            Self::PreparedIntentMismatch { detail } => write!(
                formatter,
                "the prepared message does not match the authored intent: {detail}"
            ),
            Self::ActorChainConflict { detail } => write!(
                formatter,
                "the actor chain moved under the prepared message: {detail}"
            ),
            Self::SubmissionOutcomeUnknown { detail } => write!(
                formatter,
                "the message submission result is unknown: {detail}"
            ),
            Self::Refused { code, detail } => {
                write!(formatter, "message refused ({code}): {detail}")
            }
        }
    }
}

/// Classify a transport or contract error into its recovery class.
///
/// `capability_denied` is the registered not-ready answer for an authorization
/// that exists but is not sealed yet, so it is reported as a retryable window
/// rather than as a refusal. Nothing here widens an error into a retry that the
/// contract does not allow.
pub fn classify_message_authoring_error(error: &Error) -> MessageAuthoringFailure {
    let Error::Api { status, error } = error else {
        return MessageAuthoringFailure::SubmissionOutcomeUnknown {
            detail: error.to_string(),
        };
    };
    let code = error.code().to_owned();
    let detail = error.detail.clone();
    // A stale MLS governance binding is the one refusal that means the frozen
    // encryption context itself is wrong. It is carried as a registered reason
    // code, so it is recognised without reading the human-readable detail.
    if error
        .extensions
        .get("reason_code")
        .and_then(serde_json::Value::as_str)
        == Some(arkret_wire::ReasonCode::MLS_GOVERNANCE_BINDING_STALE)
    {
        return MessageAuthoringFailure::EncryptionContextChanged { detail };
    }
    match code.as_str() {
        "capability_denied" => MessageAuthoringFailure::AuthorizationNotSealed { detail },
        "frontier_unavailable"
        | "dependency_missing"
        | "temporarily_unavailable"
        | "service_unavailable"
        | "rate_limited" => MessageAuthoringFailure::DependencyUnavailable { detail },
        "authoring_request_expired" => MessageAuthoringFailure::PreparationExpired { detail },
        "duplicate_conflict" => MessageAuthoringFailure::DuplicateConflict { detail },
        "cas_conflict" | "actor_seq_conflict" => {
            MessageAuthoringFailure::ActorChainConflict { detail }
        }
        "e2ee_required" | "plaintext_not_permitted" => {
            MessageAuthoringFailure::PlaintextRefused { detail }
        }
        "failed_precondition" if *status == 412 => {
            MessageAuthoringFailure::EncryptionContextChanged { detail }
        }
        _ => MessageAuthoringFailure::Refused { code, detail },
    }
}

/// One signed ordinary-message submission, frozen byte for byte.
///
/// Every field here is what an uncertain submit must replay unchanged. There is
/// no method that rebuilds any of it: a new attempt is a new preparation.
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PreparedMessageSubmission {
    pub request_id: RequestId,
    pub request_digest: Hash,
    pub expires_at: DateTime<Utc>,
    pub event: AuthoredEvent,
    pub canonical_body_bytes: Vec<u8>,
}

impl PreparedMessageSubmission {
    pub fn event_id(&self) -> &EventId {
        self.event.event_id()
    }

    /// The transport idempotency identity for this exact submission.
    ///
    /// It is the preparation request identity, so an exact replay after a lost
    /// response reaches the same server-side record instead of authoring a
    /// second message.
    pub fn transport_idempotency_key(&self) -> String {
        self.request_id.to_string()
    }
}

/// One user-authored ordinary message, from its frozen body to its signature.
///
/// The body is frozen at construction. `prepare` may run any number of times
/// against the same session — an exact retry sends identical canonical bytes
/// and gets the identical unsigned Event back — and none of those runs touches
/// the body, so no retry advances an MLS sender counter.
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct MessageAuthoringSession {
    request: MessagePrepareRequestBody,
    target: MessageAuthoringTarget,
    digest_suite: DigestSuite,
}

impl MessageAuthoringSession {
    /// Freeze one attempt at one user-authored message.
    ///
    /// `intent` already carries the finished body: for an encrypted target that
    /// is the envelope the host's MLS engine produced, and this constructor is
    /// the last point at which it can change.
    pub fn new(
        request_id: RequestId,
        account_id: AccountId,
        realm_id: RealmId,
        intent: MessageAuthoringIntent,
        created_at: DateTime<Utc>,
        hlc: Option<Hlc>,
        target: MessageAuthoringTarget,
        digest_suite: DigestSuite,
    ) -> Result<Self> {
        let request = MessagePrepareRequestBody {
            request_id,
            account_id,
            realm_id,
            intent,
            created_at,
            hlc,
        };
        let session = Self {
            request,
            target,
            digest_suite,
        };
        session.validate()?;
        Ok(session)
    }

    fn validate(&self) -> Result<()> {
        self.request.validate()?;
        if let MessageAuthoringContent::Mls {
            encryption_context, ..
        } = &self.request.intent.content
            && encryption_context.effective_scope != self.target.scope
        {
            return Err(Error::Protocol(
                "the encrypted body was frozen against a different effective scope".to_owned(),
            ));
        }
        if let Some(frontier) = &self.target.known_frontier {
            frontier.validate()?;
        }
        Ok(())
    }

    pub fn request(&self) -> &MessagePrepareRequestBody {
        &self.request
    }

    pub fn target(&self) -> &MessageAuthoringTarget {
        &self.target
    }

    pub fn request_id(&self) -> &RequestId {
        &self.request.request_id
    }

    pub fn expires_at(&self) -> DateTime<Utc> {
        self.request.expires_at()
    }

    /// The exact bytes the preparation request is sent as.
    ///
    /// The Station binds its answer to `SHA-256` of these bytes, so a durable
    /// record of an in-flight attempt stores them rather than re-serializing.
    pub fn canonical_request_bytes(&self) -> Result<Vec<u8>> {
        Ok(arkret_canonical::canonical_json_bytes(&self.request)?)
    }

    /// Prepare again for the same message body under a new request identity.
    ///
    /// The body is moved over verbatim. This is the recovery for an expired
    /// preparation or a definite non-acceptance, and it is exactly the case the
    /// contract says must not encrypt again.
    pub fn re_prepare(
        &self,
        request_id: RequestId,
        created_at: DateTime<Utc>,
        hlc: Option<Hlc>,
    ) -> Result<Self> {
        if request_id == self.request.request_id {
            return Err(Error::Protocol(
                "a new message preparation needs a new request identity".to_owned(),
            ));
        }
        Self::new(
            request_id,
            self.request.account_id.clone(),
            self.request.realm_id.clone(),
            self.request.intent.clone(),
            created_at,
            hlc,
            self.target.clone(),
            self.digest_suite,
        )
    }

    /// Ask the account's own Station to complete the unsigned Event.
    pub async fn prepare(
        &self,
        transport: &impl MessagePrepareTransport,
    ) -> std::result::Result<MessagePrepareOutcome, MessageAuthoringFailure> {
        let outcome = transport
            .prepare_message(&self.request)
            .await
            .map_err(|error| classify_message_authoring_error(&error))?;
        outcome
            .validate_for_request(&self.request)
            .map_err(|error| MessageAuthoringFailure::PreparedIntentMismatch {
                detail: error.to_string(),
            })?;
        Ok(outcome)
    }

    /// Check the Station answer against what this client already knows, then
    /// let the producer attach its proof and nothing else.
    ///
    /// The closure may only add proofs: the digest payload before and after is
    /// compared, so a signer that rewrites any signed member is rejected before
    /// the Event can reach a queue.
    pub fn sign<F>(
        &self,
        outcome: &MessagePrepareOutcome,
        now: DateTime<Utc>,
        sign: F,
    ) -> std::result::Result<PreparedMessageSubmission, MessageAuthoringFailure>
    where
        F: FnOnce(&mut AuthoredEvent) -> Result<()>,
    {
        let mismatch = |error: arkret_wire::WireError| {
            if error.to_string().contains("authoring_request_expired") {
                MessageAuthoringFailure::PreparationExpired {
                    detail: error.to_string(),
                }
            } else {
                MessageAuthoringFailure::PreparedIntentMismatch {
                    detail: error.to_string(),
                }
            }
        };
        let mut event = outcome
            .verify_for_signing(
                &self.request,
                &self.target.scope,
                &self.target.authorization_context,
                self.target.direct_binding.as_ref(),
                self.target.known_frontier.as_ref(),
                now,
            )
            .map_err(mismatch)?;
        let before = event.event().digest_payload().map_err(mismatch)?;
        sign(&mut event).map_err(|error| MessageAuthoringFailure::Refused {
            code: "signature_invalid".to_owned(),
            detail: error.to_string(),
        })?;
        if event.event().digest_payload().map_err(mismatch)? != before
            || !event.event().unsigned.is_empty()
        {
            return Err(MessageAuthoringFailure::PreparedIntentMismatch {
                detail: "the signer changed a prepared non-proof member".to_owned(),
            });
        }
        let suite = event.digest_suite();
        event
            .event()
            .validate_proof_bindings_with_digest_suite(suite)
            .map_err(mismatch)?;
        event
            .event()
            .validate_for_submit_structural()
            .map_err(mismatch)?;
        let canonical_body_bytes = arkret_canonical::canonical_json_bytes(&event).map_err(|e| {
            MessageAuthoringFailure::PreparedIntentMismatch {
                detail: e.to_string(),
            }
        })?;
        Ok(PreparedMessageSubmission {
            request_id: self.request.request_id.clone(),
            request_digest: outcome.request_digest.clone(),
            expires_at: outcome.expires_at,
            event,
            canonical_body_bytes,
        })
    }
}

